-- The demo v1 texts below replace whatever was active.
UPDATE public.legal_documents SET is_active = false WHERE is_active;

CREATE UNIQUE INDEX uq_legal_documents_type_version ON public.legal_documents (type, version);
CREATE UNIQUE INDEX uq_legal_documents_one_active ON public.legal_documents (type) WHERE is_active;

-- Append-only: a new version of a document means a new acceptance row, never an edited one.
CREATE TABLE public.user_legal_acceptances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users (id),
    document_id bigint NOT NULL REFERENCES public.legal_documents (id),
    accepted_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_legal_acceptances UNIQUE (user_id, document_id)
);

CREATE FUNCTION public.user_legal_acceptances_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'user_legal_acceptances is append-only';
END
$$;
CREATE TRIGGER user_legal_acceptances_append_only BEFORE UPDATE OR DELETE ON public.user_legal_acceptances
    FOR EACH ROW EXECUTE FUNCTION public.user_legal_acceptances_append_only();

