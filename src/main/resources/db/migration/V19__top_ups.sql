-- T-064: card top-ups through Stripe Checkout (sandbox). The balance is credited only by a signature-verified webhook.
CREATE TABLE public.top_ups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users (id),
    card_id bigint NOT NULL REFERENCES public.cards (id),
    amount numeric(19, 2) NOT NULL CHECK (amount > 0),
    currency character varying(3) NOT NULL,
    -- the client's Idempotency-Key: a retry returns the same checkout instead of opening a second one
    idem_key character varying(255) NOT NULL,
    stripe_session_id character varying(255) NOT NULL UNIQUE,
    checkout_url text NOT NULL,
    status character varying(16) NOT NULL CHECK (status IN ('PENDING', 'SUCCEEDED', 'EXPIRED', 'REFUND_NEEDED')),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    completed_at timestamp with time zone,
    CONSTRAINT uq_top_ups_user_key UNIQUE (user_id, idem_key)
);
CREATE INDEX idx_top_ups_user_created ON public.top_ups (user_id, created_at DESC);
