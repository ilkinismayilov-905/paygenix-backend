-- T-070/T-071: identity verification by manual admin review of an identity document.
-- The old self-check (/api/verify) compared what users typed with their own profile and set VERIFIED without
-- looking at any document, so nobody verified that way counts as verified.
ALTER TABLE public.users DROP CONSTRAINT users_verification_status_check;
UPDATE public.users SET verification_status = 'UNVERIFIED';
ALTER TABLE public.users ALTER COLUMN verification_status SET DEFAULT 'UNVERIFIED';
ALTER TABLE public.users ALTER COLUMN verification_status SET NOT NULL;
ALTER TABLE public.users ADD CONSTRAINT users_verification_status_check
    CHECK (verification_status IN ('UNVERIFIED', 'VERIFIED'));

CREATE TABLE public.kyc_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users (id),
    document_type character varying(20) NOT NULL
        CHECK (document_type IN ('ID_CARD', 'PASSPORT', 'DRIVING_LICENCE')),
    -- key in the private KYC bucket; never shown to the user, presigned for reviewers only
    document_key character varying(255) NOT NULL,
    status character varying(10) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    rejection_reason character varying(500),
    submitted_at timestamp with time zone NOT NULL DEFAULT now(),
    reviewed_at timestamp with time zone,
    reviewed_by bigint REFERENCES public.users (id),
    CONSTRAINT kyc_reviewed_fields CHECK ((status = 'PENDING') = (reviewed_at IS NULL)),
    CONSTRAINT kyc_rejection_reason CHECK ((status = 'REJECTED') = (rejection_reason IS NOT NULL))
);
-- at most one submission waiting for review per user, also under concurrent submits
CREATE UNIQUE INDEX uq_kyc_one_pending ON public.kyc_submissions (user_id) WHERE status = 'PENDING';
CREATE INDEX idx_kyc_user_submitted ON public.kyc_submissions (user_id, submitted_at DESC);
CREATE INDEX idx_kyc_status_submitted ON public.kyc_submissions (status, submitted_at);
